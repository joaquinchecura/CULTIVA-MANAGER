const allExercises = [...exercises, ...newExercises]

async function main() {
  console.log(`🌱 Iniciando seed de ejercicios...`)
  console.log(`📊 Ejercicios originales: ${exercises.length}`)
  console.log(`📊 Ejercicios nuevos: ${newExercises.length}`)
  console.log(`📊 Total a procesar: ${allExercises.length}`)

  let created = 0
  let updated = 0

  for (const exercise of allExercises) {
    const existing = await prisma.exercise.findFirst({
      where: { name: exercise.name }
    })

    if (!existing) {
      await prisma.exercise.create({
        data: {
          name: exercise.name,
          type: exercise.type,
          description: exercise.description,
          clientDescription: exercise.clientDescription,
          muscleGroup: exercise.muscleGroup,
          equipment: exercise.equipment,
          tags: exercise.tags,
          isPublic: exercise.isPublic,
        }
      })
      created++
      console.log(`✅ Creado: ${exercise.name} (${exercise.type})`)
    } else {
      await prisma.exercise.update({
        where: { id: existing.id },
        data: {
          description: exercise.description ?? existing.description,
          clientDescription: exercise.clientDescription ?? existing.clientDescription,
          muscleGroup: exercise.muscleGroup ?? existing.muscleGroup,
          equipment: exercise.equipment ?? existing.equipment,
          tags: exercise.tags ?? existing.tags,
        }
      })
      updated++
      console.log(`🔄 Actualizado: ${exercise.name}`)
    }
  }

  const totalInDb = await prisma.exercise.count()
  console.log(`\n🎉 Seed completado!`)
  console.log(`   Creados: ${created}`)
  console.log(`   Actualizados: ${updated}`)
  console.log(`   Total en base de datos: ${totalInDb}`)
}

main()
  .catch((e) => {
    console.error(e)
    process.exit(1)
  })
  .finally(async () => {
    await prisma.$disconnect()
  })